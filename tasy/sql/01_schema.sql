-- Mock de HIS + faturamento no estilo TASY (rede hospitalar privada), para o conector SQL generico do QIMED.
-- Estilo, nao copia: tabelas e colunas em maiusculas, nomes em portugues, prefixos CD_/DS_/DT_/IE_/NR_/QT_/VL_,
-- codigos proprios em IE_* e auditoria DT_ATUALIZACAO/NM_USUARIO em toda tabela. Dicionario: mocks/tasy/README.md.
--
-- SQL em subconjunto portavel (MariaDB e SQLite) para os testes rodarem o mesmo schema sem container:
-- sem AUTO_INCREMENT, sem ENGINE, sem tipos proprios do MariaDB.

-- Cadastros -----------------------------------------------------------------------------------------------------

CREATE TABLE ESTABELECIMENTO (
    CD_ESTABELECIMENTO   INT          NOT NULL PRIMARY KEY,
    NM_FANTASIA          VARCHAR(80)  NOT NULL,
    CD_CNES              VARCHAR(7)   NOT NULL,
    DT_ATUALIZACAO       DATETIME     NOT NULL,
    NM_USUARIO           VARCHAR(15)  NOT NULL
);

CREATE TABLE ESPECIALIDADE_MEDICA (
    CD_ESPECIALIDADE     INT          NOT NULL PRIMARY KEY,
    DS_ESPECIALIDADE     VARCHAR(60)  NOT NULL,
    DT_ATUALIZACAO       DATETIME     NOT NULL,
    NM_USUARIO           VARCHAR(15)  NOT NULL
);

-- CD_CLASSIF_SETOR: 1 pronto-socorro, 3 internacao, 4 UTI, 8 ambulatorio
CREATE TABLE SETOR_ATENDIMENTO (
    CD_SETOR_ATENDIMENTO INT          NOT NULL PRIMARY KEY,
    CD_ESTABELECIMENTO   INT          NOT NULL REFERENCES ESTABELECIMENTO (CD_ESTABELECIMENTO),
    DS_SETOR_ATENDIMENTO VARCHAR(60)  NOT NULL,
    CD_CLASSIF_SETOR     INT          NOT NULL,
    IE_SITUACAO          CHAR(1)      NOT NULL,          -- A ativo, I inativo
    DT_ATUALIZACAO       DATETIME     NOT NULL,
    NM_USUARIO           VARCHAR(15)  NOT NULL
);

-- Leitos. IE_STATUS_UNIDADE: L livre, P ocupado (paciente), H higienizacao, I interditado
CREATE TABLE UNIDADE_ATENDIMENTO (
    NR_SEQ_INTERNO       INT          NOT NULL PRIMARY KEY,
    CD_SETOR_ATENDIMENTO INT          NOT NULL REFERENCES SETOR_ATENDIMENTO (CD_SETOR_ATENDIMENTO),
    CD_UNIDADE_BASICA    VARCHAR(10)  NOT NULL,          -- quarto
    CD_UNIDADE_COMPL     VARCHAR(10)  NOT NULL,          -- leito
    IE_STATUS_UNIDADE    CHAR(1)      NOT NULL,
    DT_ATUALIZACAO       DATETIME     NOT NULL,
    NM_USUARIO           VARCHAR(15)  NOT NULL
);

-- IE_TIPO_CONVENIO: 1 particular, 2 convenio (operadora), 3 SUS
CREATE TABLE CONVENIO (
    CD_CONVENIO          INT          NOT NULL PRIMARY KEY,
    DS_CONVENIO          VARCHAR(60)  NOT NULL,
    IE_TIPO_CONVENIO     INT          NOT NULL,
    CD_REGISTRO_ANS      VARCHAR(6),
    QT_DIAS_PRAZO_ENVIO  INT          NOT NULL,          -- prazo contratual para enviar a conta
    DT_ATUALIZACAO       DATETIME     NOT NULL,
    NM_USUARIO           VARCHAR(15)  NOT NULL
);

CREATE TABLE MOTIVO_ALTA (
    CD_MOTIVO_ALTA       INT          NOT NULL PRIMARY KEY,
    DS_MOTIVO_ALTA       VARCHAR(60)  NOT NULL,
    IE_OBITO             CHAR(1)      NOT NULL,          -- S/N
    DT_ATUALIZACAO       DATETIME     NOT NULL,
    NM_USUARIO           VARCHAR(15)  NOT NULL
);

-- CD_MOTIVO_TISS: codigo no formato da tabela de glosas do TISS; os valores do mock sao ficticios
CREATE TABLE MOTIVO_GLOSA (
    CD_MOTIVO_GLOSA      INT          NOT NULL PRIMARY KEY,
    DS_MOTIVO_GLOSA      VARCHAR(80)  NOT NULL,
    CD_MOTIVO_TISS       VARCHAR(4),
    DT_ATUALIZACAO       DATETIME     NOT NULL,
    NM_USUARIO           VARCHAR(15)  NOT NULL
);

-- IE_ORIGEM_PROCED: 8 tabela propria do hospital (codigos e valores ficticios)
CREATE TABLE PROCEDIMENTO (
    CD_PROCEDIMENTO      VARCHAR(10)  NOT NULL PRIMARY KEY,
    DS_PROCEDIMENTO      VARCHAR(80)  NOT NULL,
    IE_ORIGEM_PROCED     INT          NOT NULL,
    IE_EXIGE_AUTORIZACAO CHAR(1)      NOT NULL,          -- S/N
    VL_REFERENCIA        DECIMAL(15,2) NOT NULL,
    DT_ATUALIZACAO       DATETIME     NOT NULL,
    NM_USUARIO           VARCHAR(15)  NOT NULL
);

CREATE TABLE MATERIAL (
    CD_MATERIAL          INT          NOT NULL PRIMARY KEY,
    DS_MATERIAL          VARCHAR(80)  NOT NULL,
    IE_ALTO_CUSTO        CHAR(1)      NOT NULL,          -- S/N
    VL_REFERENCIA        DECIMAL(15,2) NOT NULL,
    DT_ATUALIZACAO       DATETIME     NOT NULL,
    NM_USUARIO           VARCHAR(15)  NOT NULL
);

-- Pacientes e profissionais na mesma tabela, como no TASY. IE_FUNCIONARIO: S profissional, N paciente
CREATE TABLE PESSOA_FISICA (
    CD_PESSOA_FISICA     VARCHAR(10)  NOT NULL PRIMARY KEY,
    NM_PESSOA_FISICA     VARCHAR(80)  NOT NULL,
    DT_NASCIMENTO        DATE,
    IE_SEXO              CHAR(1),                        -- M, F, I (indeterminado)
    NR_CPF               VARCHAR(11),
    NR_CARTAO_NAC_SUS    VARCHAR(15),
    NM_MAE               VARCHAR(80),
    NR_TELEFONE_CELULAR  VARCHAR(15),
    DT_OBITO             DATE,
    IE_FUNCIONARIO       CHAR(1)      NOT NULL,
    DT_ATUALIZACAO       DATETIME     NOT NULL,
    NM_USUARIO           VARCHAR(15)  NOT NULL
);

CREATE TABLE MEDICO (
    CD_PESSOA_FISICA     VARCHAR(10)  NOT NULL PRIMARY KEY REFERENCES PESSOA_FISICA (CD_PESSOA_FISICA),
    NR_CRM               VARCHAR(10)  NOT NULL,
    UF_CRM               CHAR(2)      NOT NULL,
    CD_ESPECIALIDADE     INT          NOT NULL REFERENCES ESPECIALIDADE_MEDICA (CD_ESPECIALIDADE),
    IE_SITUACAO          CHAR(1)      NOT NULL,
    DT_ATUALIZACAO       DATETIME     NOT NULL,
    NM_USUARIO           VARCHAR(15)  NOT NULL
);

-- Assistencial ---------------------------------------------------------------------------------------------------

-- IE_TIPO_ATENDIMENTO: 1 internado, 3 pronto-socorro, 8 ambulatorial. IE_CARATER_ATENDIMENTO: E eletivo, U urgencia
CREATE TABLE ATENDIMENTO_PACIENTE (
    NR_ATENDIMENTO       INT          NOT NULL PRIMARY KEY,
    CD_ESTABELECIMENTO   INT          NOT NULL REFERENCES ESTABELECIMENTO (CD_ESTABELECIMENTO),
    CD_PESSOA_FISICA     VARCHAR(10)  NOT NULL REFERENCES PESSOA_FISICA (CD_PESSOA_FISICA),
    IE_TIPO_ATENDIMENTO  INT          NOT NULL,
    IE_CARATER_ATENDIMENTO CHAR(1)    NOT NULL,
    DT_ENTRADA           DATETIME     NOT NULL,
    DT_ALTA              DATETIME,
    CD_MOTIVO_ALTA       INT          REFERENCES MOTIVO_ALTA (CD_MOTIVO_ALTA),
    CD_MEDICO_RESP       VARCHAR(10)  REFERENCES MEDICO (CD_PESSOA_FISICA),
    DT_ATUALIZACAO       DATETIME     NOT NULL,
    NM_USUARIO           VARCHAR(15)  NOT NULL
);

-- Convenio do atendimento. CD_SENHA = senha de autorizacao da operadora (nula quando nao foi pedida)
CREATE TABLE ATEND_CATEGORIA_CONVENIO (
    NR_SEQ_INTERNO       INT          NOT NULL PRIMARY KEY,
    NR_ATENDIMENTO       INT          NOT NULL REFERENCES ATENDIMENTO_PACIENTE (NR_ATENDIMENTO),
    CD_CONVENIO          INT          NOT NULL REFERENCES CONVENIO (CD_CONVENIO),
    CD_CATEGORIA         VARCHAR(10)  NOT NULL,          -- plano/categoria dentro do convenio
    NR_DOC_CONVENIO      VARCHAR(20),                    -- carteirinha
    CD_SENHA             VARCHAR(20),
    DT_INICIO_VIGENCIA   DATETIME     NOT NULL,
    DT_ATUALIZACAO       DATETIME     NOT NULL,
    NM_USUARIO           VARCHAR(15)  NOT NULL
);

-- CID-10 sem ponto. IE_CLASSIFICACAO_DOENCA: P principal, S secundario
CREATE TABLE DIAGNOSTICO_DOENCA (
    NR_SEQUENCIA         INT          NOT NULL PRIMARY KEY,
    NR_ATENDIMENTO       INT          NOT NULL REFERENCES ATENDIMENTO_PACIENTE (NR_ATENDIMENTO),
    CD_DOENCA            VARCHAR(10)  NOT NULL,
    IE_CLASSIFICACAO_DOENCA CHAR(1)   NOT NULL,
    DT_DIAGNOSTICO       DATETIME     NOT NULL,
    CD_MEDICO            VARCHAR(10)  REFERENCES MEDICO (CD_PESSOA_FISICA),
    DT_ATUALIZACAO       DATETIME     NOT NULL,
    NM_USUARIO           VARCHAR(15)  NOT NULL
);

-- Passagem do paciente por setor e leito (censo)
CREATE TABLE ATEND_PACIENTE_UNIDADE (
    NR_SEQ_INTERNO       INT          NOT NULL PRIMARY KEY,
    NR_ATENDIMENTO       INT          NOT NULL REFERENCES ATENDIMENTO_PACIENTE (NR_ATENDIMENTO),
    CD_SETOR_ATENDIMENTO INT          NOT NULL REFERENCES SETOR_ATENDIMENTO (CD_SETOR_ATENDIMENTO),
    NR_SEQ_UNIDADE       INT          REFERENCES UNIDADE_ATENDIMENTO (NR_SEQ_INTERNO),
    DT_ENTRADA_UNIDADE   DATETIME     NOT NULL,
    DT_SAIDA_UNIDADE     DATETIME,
    DT_ATUALIZACAO       DATETIME     NOT NULL,
    NM_USUARIO           VARCHAR(15)  NOT NULL
);

-- Escala de plantao. IE_FUNCAO: M medico, E enfermeiro, T tecnico de enfermagem.
-- IE_SITUACAO: P prevista, R realizada, F falta
CREATE TABLE ESCALA_PLANTAO (
    NR_SEQUENCIA         INT          NOT NULL PRIMARY KEY,
    CD_PESSOA_FISICA     VARCHAR(10)  NOT NULL REFERENCES PESSOA_FISICA (CD_PESSOA_FISICA),
    CD_SETOR_ATENDIMENTO INT          NOT NULL REFERENCES SETOR_ATENDIMENTO (CD_SETOR_ATENDIMENTO),
    IE_FUNCAO            CHAR(1)      NOT NULL,
    DT_INICIO            DATETIME     NOT NULL,
    DT_FIM               DATETIME     NOT NULL,
    IE_SITUACAO          CHAR(1)      NOT NULL,
    DT_ATUALIZACAO       DATETIME     NOT NULL,
    NM_USUARIO           VARCHAR(15)  NOT NULL
);

-- Faturamento ----------------------------------------------------------------------------------------------------

-- IE_STATUS_ACERTO: 1 provisoria (aberta), 2 definitiva (fechada). NR_SEQ_PROTOCOLO = lote enviado a operadora
CREATE TABLE CONTA_PACIENTE (
    NR_INTERNO_CONTA     INT          NOT NULL PRIMARY KEY,
    NR_ATENDIMENTO       INT          NOT NULL REFERENCES ATENDIMENTO_PACIENTE (NR_ATENDIMENTO),
    CD_CONVENIO_PARAMETRO INT         NOT NULL REFERENCES CONVENIO (CD_CONVENIO),
    DT_MESANO_REFERENCIA DATE         NOT NULL,
    IE_STATUS_ACERTO     INT          NOT NULL,
    VL_CONTA             DECIMAL(15,2) NOT NULL,
    NR_SEQ_PROTOCOLO     INT,
    DT_ENVIO_PROTOCOLO   DATETIME,
    DT_ATUALIZACAO       DATETIME     NOT NULL,
    NM_USUARIO           VARCHAR(15)  NOT NULL
);

CREATE TABLE PROCEDIMENTO_PACIENTE (
    NR_SEQUENCIA         INT          NOT NULL PRIMARY KEY,
    NR_INTERNO_CONTA     INT          NOT NULL REFERENCES CONTA_PACIENTE (NR_INTERNO_CONTA),
    NR_ATENDIMENTO       INT          NOT NULL REFERENCES ATENDIMENTO_PACIENTE (NR_ATENDIMENTO),
    CD_PROCEDIMENTO      VARCHAR(10)  NOT NULL REFERENCES PROCEDIMENTO (CD_PROCEDIMENTO),
    DT_PROCEDIMENTO      DATETIME     NOT NULL,
    QT_PROCEDIMENTO      DECIMAL(9,2) NOT NULL,
    VL_PROCEDIMENTO      DECIMAL(15,2) NOT NULL,
    CD_MEDICO_EXECUTOR   VARCHAR(10)  REFERENCES MEDICO (CD_PESSOA_FISICA),
    DT_ATUALIZACAO       DATETIME     NOT NULL,
    NM_USUARIO           VARCHAR(15)  NOT NULL
);

CREATE TABLE MATERIAL_ATEND_PACIENTE (
    NR_SEQUENCIA         INT          NOT NULL PRIMARY KEY,
    NR_INTERNO_CONTA     INT          NOT NULL REFERENCES CONTA_PACIENTE (NR_INTERNO_CONTA),
    NR_ATENDIMENTO       INT          NOT NULL REFERENCES ATENDIMENTO_PACIENTE (NR_ATENDIMENTO),
    CD_MATERIAL          INT          NOT NULL REFERENCES MATERIAL (CD_MATERIAL),
    DT_ATENDIMENTO       DATETIME     NOT NULL,
    QT_MATERIAL          DECIMAL(9,2) NOT NULL,
    VL_MATERIAL          DECIMAL(15,2) NOT NULL,
    DT_ATUALIZACAO       DATETIME     NOT NULL,
    NM_USUARIO           VARCHAR(15)  NOT NULL
);

-- Retorno (demonstrativo de pagamento) da operadora, por lote enviado
CREATE TABLE CONVENIO_RETORNO (
    NR_SEQUENCIA         INT          NOT NULL PRIMARY KEY,
    CD_CONVENIO          INT          NOT NULL REFERENCES CONVENIO (CD_CONVENIO),
    NR_SEQ_PROTOCOLO     INT          NOT NULL,
    DT_RETORNO           DATETIME     NOT NULL,
    DT_ATUALIZACAO       DATETIME     NOT NULL,
    NM_USUARIO           VARCHAR(15)  NOT NULL
);

-- Um item por procedimento ou material cobrado; VL_GLOSADO > 0 com CD_MOTIVO_GLOSA quando houve glosa
CREATE TABLE CONVENIO_RETORNO_ITEM (
    NR_SEQUENCIA         INT          NOT NULL PRIMARY KEY,
    NR_SEQ_RETORNO       INT          NOT NULL REFERENCES CONVENIO_RETORNO (NR_SEQUENCIA),
    NR_INTERNO_CONTA     INT          NOT NULL REFERENCES CONTA_PACIENTE (NR_INTERNO_CONTA),
    NR_SEQ_PROCED        INT          REFERENCES PROCEDIMENTO_PACIENTE (NR_SEQUENCIA),
    NR_SEQ_MATERIAL      INT          REFERENCES MATERIAL_ATEND_PACIENTE (NR_SEQUENCIA),
    VL_COBRADO           DECIMAL(15,2) NOT NULL,
    VL_PAGO              DECIMAL(15,2) NOT NULL,
    VL_GLOSADO           DECIMAL(15,2) NOT NULL,
    CD_MOTIVO_GLOSA      INT          REFERENCES MOTIVO_GLOSA (CD_MOTIVO_GLOSA),
    DT_ATUALIZACAO       DATETIME     NOT NULL,
    NM_USUARIO           VARCHAR(15)  NOT NULL
);
